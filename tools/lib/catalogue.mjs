// Generates the public files of the tap: Casks/<slug>.rb and README.md (the catalogue).
// The catalogue data lives in apps/<slug>.json; `ship` refreshes it from each app's app.json.
// Run directly to regenerate README.md:  node tools/lib/catalogue.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TAP_FULL, TAP_ROOT, TAP_URL, assetName, catalogueUrl, feedUrl, releaseTag } from './config.mjs';

const MACOS = { 12: 'monterey', 13: 'ventura', 14: 'sonoma', 15: 'sequoia', 26: 'tahoe' };
const MACOS_NAME = { 12: 'Monterey', 13: 'Ventura', 14: 'Sonoma', 15: 'Sequoia', 26: 'Tahoe' };

const rb = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/#\{/g, '\\#{');

// Homebrew wants a short desc without the app name in front and without a final period.
export function caskDesc(name, tagline) {
  let d = String(tagline || name).trim().replace(/\.+$/, '');
  if (d.toLowerCase().startsWith(name.toLowerCase())) d = d.slice(name.length).replace(/^[\s:—–-]+/, '');
  return d.charAt(0).toUpperCase() + d.slice(1);
}

export function renderCask(a) {
  const { slug, name, tagline, version, sha256, appName, bundleId, archs = [], minOS, autoUpdates } = a;
  const url = a.url || `${TAP_URL}/releases/download/${releaseTag(slug, '#{version}')}/${assetName(slug, '#{version}')}`;
  const major = minOS ? Number(String(minOS).split('.')[0]) : 0;
  const deps = [];
  if (archs.length === 1 && archs[0] === 'arm64') deps.push('  depends_on arch: :arm64');
  if (archs.length === 1 && archs[0] === 'x86_64') deps.push('  depends_on arch: :x86_64');
  if (MACOS[major]) deps.push(`  depends_on macos: ">= :${MACOS[major]}"`);
  const zap = bundleId
    ? [
        `~/Library/Application Support/${bundleId}`,
        `~/Library/Caches/${bundleId}`,
        `~/Library/HTTPStorages/${bundleId}`,
        `~/Library/Preferences/${bundleId}.plist`,
        `~/Library/Saved Application State/${bundleId}.savedState`,
        `~/Library/WebKit/${bundleId}`,
      ]
    : [];
  return `# Generated by tools/ship from ${appName} ${version}. Do not edit by hand: the next release overwrites it.
cask "${slug}" do
  version "${rb(version)}"
  sha256 "${sha256}"

  url "${url}"
  name "${rb(name)}"
  desc "${rb(caskDesc(name, tagline))}"
  homepage "${catalogueUrl(slug)}"
${autoUpdates ? '\n  auto_updates true\n' : ''}${deps.length ? '\n' + deps.join('\n') + '\n' : ''}
  app "${rb(appName)}"
${zap.length ? `\n  zap trash: [\n${zap.map((p) => `    "${rb(p)}",`).join('\n')}\n  ]\n` : ''}
  caveats <<~EOS
    ${rb(name)} is signed with the SAASEmpiree self-signed certificate, not notarized by Apple.
    If macOS refuses to open it the first time, run once:
      xattr -dr com.apple.quarantine "#{appdir}/${rb(appName)}"
  EOS
end
`;
}

export function caskVersion(text) {
  const m = /^\s*version\s+"([^"]+)"/m.exec(text || '');
  return m ? m[1] : null;
}

export function loadApps(root = TAP_ROOT) {
  const dir = join(root, 'apps');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
    .sort((a, b) => (a.order ?? 999) - (b.order ?? 999) || a.name.localeCompare(b.name));
}

const headingSlug = (s) =>
  s.toLowerCase().replace(/<[^>]+>/g, '').trim().replace(/[^\p{L}\p{N}\s-]/gu, '').replace(/\s/g, '-');

function platformLine(a, rel) {
  const parts = [];
  if ((a.platforms || []).includes('macos')) {
    const min = rel?.minOS || a.minOS;
    const major = min ? Number(String(min).split('.')[0]) : 0;
    let mac = 'macOS';
    if (min) mac += ` ${major >= 11 ? major : min}+${MACOS_NAME[major] ? ` (${MACOS_NAME[major]})` : ''}`;
    const archs = rel?.archs || a.archs || [];
    if (archs.length === 1 && archs[0] === 'arm64') mac += ' · Apple Silicon';
    else if (archs.includes('arm64') && archs.includes('x86_64')) mac += ' · Apple Silicon & Intel';
    parts.push(mac);
  }
  if ((a.platforms || []).includes('windows')) parts.push('Windows 10+');
  return parts.join(' · ');
}

const STACK = { swift: 'Swift · SwiftUI', tauri: 'Tauri · Rust', electron: 'Electron' };

function updatesText(a) {
  if (a.update === 'sparkle')
    return `Updates itself in the background with [Sparkle](https://sparkle-project.org): it checks once a day against the signed feed [\`appcasts/${a.slug}.xml\`](appcasts/${a.slug}.xml). Homebrew leaves it alone (\`auto_updates true\`).`;
  if (a.update === 'own') return a.updateNote || 'Updates itself through its own release pipeline.';
  return `Through Homebrew: \`brew upgrade --cask ${a.slug}\` (or \`brew upgrade\` for everything).`;
}

function section(a, root) {
  const caskPath = join(root, 'Casks', `${a.slug}.rb`);
  const version = existsSync(caskPath) ? caskVersion(readFileSync(caskPath, 'utf8')) : null;
  const rel = a.release || null;
  const icon = existsSync(join(root, 'icons', `${a.slug}.png`)) ? `<img src="icons/${a.slug}.png" width="28" height="28" align="center" alt=""> ` : '';
  const out = [];
  if (headingSlug(a.name) !== a.slug) out.push(`<a name="${a.slug}"></a>`);
  out.push(`### ${icon}${a.name}`, '');
  if (a.tagline) out.push(`**${a.tagline}**`, '');
  if (a.description) out.push(a.description.trim(), '');
  const rows = [['Platform', platformLine(a, rel)], ['Stack', STACK[a.stack] || a.stack || '']];
  if (version) rows.push(['Latest', `[${version}](${TAP_URL}/releases/tag/${releaseTag(a.slug, version)})`]);
  else if (a.update !== 'own') rows.push(['Latest', 'first release pending']);
  out.push('| | |', '|---|---|', ...rows.filter((r) => r[1]).map(([k, v]) => `| ${k} | ${v} |`), '');
  out.push('**Install**', '');
  if (a.installNote) out.push(a.installNote, '');
  else if ((a.platforms || []).includes('macos')) {
    out.push('```sh', `brew install --cask saasempiree/tap/${a.slug}`, '```', '');
    if (!version) out.push(`_The cask is published with ${a.name}'s first release from this tap; until then the command above reports “no cask”._`, '');
  }
  if (a.scoop) out.push('Windows ([Scoop](https://scoop.sh)):', '', '```powershell', 'scoop bucket add saasempiree https://github.com/SAASEmpiree/homebrew-tap', `scoop install saasempiree/${a.scoop}`, '```', '');
  out.push(`**Updates**: ${updatesText(a)}`, '');
  return out.join('\n');
}

export function renderReadme(root = TAP_ROOT) {
  const apps = loadApps(root);
  const rowsFor = (a) => {
    const caskPath = join(root, 'Casks', `${a.slug}.rb`);
    const v = existsSync(caskPath) ? caskVersion(readFileSync(caskPath, 'utf8')) : null;
    const status = a.update === 'own' ? 'own pipeline' : v || 'pending';
    return `| [${a.name}](#${a.slug}) | ${a.tagline || ''} | ${status} |`;
  };
  return `<!-- Generated by tools/lib/catalogue.mjs from apps/*.json and Casks/*.rb. Edit those, not this file. -->
<div align="center">

# SAASEmpiree apps

**Every SAASEmpiree app, installed and updated from one place.**

[![Homebrew tap](https://img.shields.io/badge/brew-saasempiree%2Ftap-FBB040?style=flat-square&logo=homebrew&logoColor=white)](#quick-start)
[![Scoop bucket](https://img.shields.io/badge/scoop-saasempiree-5391FE?style=flat-square&logo=windows&logoColor=white)](#windows)
[![Apps](https://img.shields.io/badge/apps-${apps.length}-0a0a0c?style=flat-square)](#catalogue)

</div>

Small, local-first apps for macOS (and Windows for some). The code of each app lives in a private repository; this public repository is the distribution hub: Homebrew casks, Scoop manifests, Sparkle update feeds, and the GitHub Releases that hold every binary.

## Quick start

\`\`\`sh
brew tap saasempiree/tap
brew install --cask saasempiree/tap/<app>      # e.g. saasempiree/tap/units
\`\`\`

Upgrade everything installed from this tap with \`brew upgrade\`. Apps marked **Sparkle** update themselves.

> [!NOTE]
> The apps are signed with a self-signed certificate (stable across updates, so macOS keeps the permissions you grant), but they are not notarized by Apple. If macOS says an app “cannot be opened” the first time, run once:
> \`xattr -dr com.apple.quarantine "/Applications/<App>.app"\`

### Windows

\`\`\`powershell
scoop bucket add saasempiree https://github.com/SAASEmpiree/homebrew-tap
scoop install saasempiree/<app>
\`\`\`

## Catalogue

| App | What it does | Latest |
|---|---|---|
${apps.map(rowsFor).join('\n')}

${apps.map((a) => section(a, root)).join('\n---\n\n')}
---

## How this tap works

| Path | What it holds |
|---|---|
| \`Casks/<app>.rb\` | Homebrew casks, generated at each release (version + sha256). |
| \`bucket/<app>.json\` | Scoop manifests for the Windows builds. |
| \`appcasts/<app>.xml\` | Sparkle feeds (EdDSA-signed items), served from \`${feedUrl('<app>')}\`. |
| \`apps/<app>.json\` | Catalogue data this README is generated from. |
| \`icons/<app>.png\` | App icons used above. |
| [Releases](${TAP_URL}/releases) | One release per app version, tagged \`<app>-v<version>\`, holding the zipped \`.app\`. |
| \`tools/\` | \`ship\`, \`sync-after-install\` and \`audit\`, the scripts that publish a release and keep GitHub equal to what is installed. See [tools/README.md](tools/README.md). |

Releases are cut by \`tools/ship\` (or \`tools/sync-after-install\` at the end of an app's install script): it tags the app's private repo, uploads the zipped \`.app\` here, regenerates the cask and, for Sparkle apps, the signed appcast. Nothing in this repository is edited by hand except \`apps/*.json\` descriptions and \`tools/\`.

## License

Each app keeps its own license. The tap's scripts and metadata: © SAASEmpiree, all rights reserved.
`;
}

export function writeReadme(root = TAP_ROOT) {
  const p = join(root, 'README.md');
  const next = renderReadme(root);
  const prev = existsSync(p) ? readFileSync(p, 'utf8') : '';
  if (prev !== next) writeFileSync(p, next);
  return prev !== next;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(writeReadme() ? `README.md regenerated (${TAP_FULL}).` : 'README.md already up to date.');
}
